export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE
}

export function loadLocale() {
  try {
    return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY))
  } catch (_error) {
    return DEFAULT_LOCALE
  }
}

export function saveLocale(locale) {
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, normalizeLocale(locale))
  } catch (_error) {
    // Language switching still works if storage is unavailable.
  }
}

export function translate(locale, key, params = {}) {
  const selected = messages[normalizeLocale(locale)]
  const message = selected[key] || messages[DEFAULT_LOCALE][key] || key
  return message.replace(/\{([a-zA-Z]+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match)
}

const I18nContext = createContext({ locale: DEFAULT_LOCALE, t: (key, params) => translate(DEFAULT_LOCALE, key, params) })

export function I18nProvider({ locale, children }) {
  const normalized = normalizeLocale(locale)
  return <I18nContext.Provider value={{ locale: normalized, t: (key, params) => translate(normalized, key, params) }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
